import { Router } from 'express';
import { authenticateToken, requireAdmin, AuthRequest } from '../middleware/auth.middleware';
import { DeliveryController as C } from '../controllers/delivery.controller';
import { sendError } from '../utils/response';
import { RiderApplicationController as A } from '../controllers/rider-application.controller';
import { RiderTrackingController as T } from '../controllers/rider-tracking.controller';
const router = Router();
router.use(authenticateToken);
router.get('/application', A.get);
router.put('/application', A.save);
router.post('/application/submit', A.submit);
router.get('/applications/:id', requireAdmin, A.get);
router.get('/applications/:id/documents/:type', A.image);
router.put('/applications/:id/documents/:type/review', requireAdmin, A.reviewDocument);
router.get('/operations', requireAdmin, C.operations);
router.put('/riders', requireAdmin, C.riderAccount);
router.put('/riders/:id/review', requireAdmin, C.reviewRider);
router.put('/orders/:id/assign', requireAdmin, C.assign);
router.get('/orders/:id/rider-options', requireAdmin, C.riderOptions);
router.get('/rider', (req: AuthRequest, res, next) => req.user?.isRider ? next() : sendError(res, 'Rider access required', 'FORBIDDEN', 403), C.jobs);
router.put('/location', (req: AuthRequest, res, next) => req.user?.isRider ? next() : sendError(res, 'Rider access required', 'FORBIDDEN', 403), T.update);
router.get('/orders/:id/tracking', T.get);
router.get('/orders/:id/route-preview', C.routePreview);
router.get('/available-jobs', (req: AuthRequest, res, next) => req.user?.isRider ? next() : sendError(res, 'Rider access required', 'FORBIDDEN', 403), C.availableJobs);
router.put('/orders/:id/claim', (req: AuthRequest, res, next) => req.user?.isRider ? next() : sendError(res, 'Rider access required', 'FORBIDDEN', 403), C.claim);
router.put('/availability', (req: AuthRequest, res, next) => req.user?.isRider ? next() : sendError(res, 'Rider access required', 'FORBIDDEN', 403), C.availability);
router.put('/assignments/:id/respond', (req: AuthRequest, res, next) => req.user?.isRider ? next() : sendError(res, 'Rider access required', 'FORBIDDEN', 403), C.respond);
router.get('/orders/:id', C.detail);
router.get('/orders/:id/weight-evidence/:evidenceId', C.weightImage);
router.put('/orders/:id/action', C.action);
export default router;
